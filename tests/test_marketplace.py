    def test_oracle_schema_compiles_identity_columns_and_legacy_booleans(self):
        dialect = oracle_dialect()
        dialect.server_version_info = (19, 3)
        dialect.supports_native_boolean = False
        dialect.supports_identity_columns = True
        statements = [
            str(CreateTable(table).compile(dialect=dialect))
            for table in db.metadata.sorted_tables
        ]

        identity_column_count = sum(
            1 for table in db.metadata.sorted_tables
            for column in table.columns
            if column.identity is not None
        )
        self.assertEqual(
            sum("GENERATED BY DEFAULT AS IDENTITY" in statement for statement in statements),
            identity_column_count,
        )
        self.assertGreater(identity_column_count, 0)
        self.assertIn("is_active SMALLINT", next(
            statement for statement in statements if "CREATE TABLE users" in statement
        ))

